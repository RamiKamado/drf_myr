function pairArmProbability(drm, arm, pair) {
    const results = [];
    for (const moves in PAIR_ARM_RAW_DATA) {
        const key = `${moves}_${drm}_${arm}_${pair}`;
        if (PAIR_ARM_DATA.has(key)) {
            results.push({ moves: +moves, prob: PAIR_ARM_DATA.get(key) });
        }
    }
    results.sort((a, b) => a.moves - b.moves);
    return results;
}

function probabilityBadgeColor(p) {
    if (p <= 0) return "#7f8c8d"; // 0% = グレー
    const red = [231, 76, 60];
    const yellow = [241, 196, 15];
    const green = [39, 174, 96];
    let t, c1, c2;
    if (p <= 50) {
        t = p / 50;
        c1 = red; c2 = yellow;
    } else {
        t = (p - 50) / 50;
        c1 = yellow; c2 = green;
    }
    const r = Math.round(c1[0] + (c2[0]-c1[0])*t);
    const g = Math.round(c1[1] + (c2[1]-c1[1])*t);
    const b = Math.round(c1[2] + (c2[2]-c1[2])*t);
    return `rgb(${r},${g},${b})`;
}

function pairArmProbabilityHtml(drm, arm, pair) {
    const results = pairArmProbability(drm, arm, pair);
    if (results.length==0) return "";
    return " " + results.map(r => {
        const color = probabilityBadgeColor(r.prob);
        return `<span class="tag" style="background-color:${color};color:white;">${r.moves}-moves: ${r.prob.toFixed(1)}%</span>`;
    }).join(" ");
}

