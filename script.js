elRandom.addEventListener("click", () => {
    // TODO: ランダム状態にしたい。
    const scramble = ["R'", "U'", "F"];

    function rand(n) {
        let r = Math.random()*n|0;
        if (r<0 || n<=r) {
            r = 0;
        }
        return r;
    }

    for (let i=0; i<24; i++) {
        while (true) {
            const m = ["F", "B", "R", "L", "U", "D"][rand(6)]+["", "2", "'"][rand(3)];
            last = scramble[scramble.length-1];
            if (m[0]==last[0] ||
                m[0]=="F" && last[0]=="B" ||
                m[0]=="R" && last[0]=="L" ||
                m[0]=="U" && last[0]=="D" ||
                i==23 && (m[0]=="R" || m[0][0]=="L")) {
                continue;
            }
            scramble.push(m);
            break;
        }
    }

    scramble.push("R'", "U'", "F");

    elInput.value = scramble.join(" ");
    search();
});

for (let b of document.getElementsByClassName("key")) {
    let v = b.textContent;
    if (v=="←") {
        v = "\n";
    }
    b.addEventListener("click", () => {
        const t = elInput.value;
        const p = elInput.selectionStart || 0;
        let t2 = t.substring(0, p);
        let add = 0;
        if (0<p && t[p-1]!=" ") {
            t2 += " ";
            add++;
        }
        t2 += v;
        if (p<t.length && t[p]!=" ") {
            t2 += " ";
            add++;
        }
        add += v.length;
        t2 += t.substring(p);
        elInput.value = t2;
        setTimeout(() => {
            elInput.setSelectionRange(p+add, p+add);
        }, 0);
    });
}

